"""Create Jira stories directly from RIA user stories (Jira REST API v2: POST /rest/api/2/issue).

* Jira Cloud: Basic auth with account email + API token.
* Jira Data Center / Server: Bearer personal access token (leave the email empty).
* Simulation mode builds the exact same payloads but never calls the network. It returns SIM-n keys,
  so the flow can be demonstrated without credentials or company data leaving the machine.

API v2 is used because its ``description`` accepts plain wiki-markup text (v3 on Cloud requires ADF JSON).
"""
from __future__ import annotations

import base64
import re
from dataclasses import dataclass, field

import httpx

from ria.models.analysis import RequirementRecord, StoryRecord, TestScenarioRecord
from ria.logging_setup import ctx, get_logger

log = get_logger(__name__)


SUMMARY_MAX = 250            # Jira's summary limit is 255 characters
_LABEL_BAD = re.compile(r"[^A-Za-z0-9_.-]+")


class JiraError(RuntimeError):
    pass


@dataclass
class JiraConfig:
    base_url: str = ""
    email: str = ""
    api_token: str = ""
    project_key: str = ""
    issue_type: str = "Story"
    simulation: bool = True

    @property
    def missing(self) -> list[str]:
        need = {"JIRA_BASE_URL": self.base_url, "JIRA_API_TOKEN": self.api_token, "JIRA_PROJECT_KEY": self.project_key}
        return [k for k, v in need.items() if not v]

    @property
    def is_cloud(self) -> bool:
        return bool(self.email)

    @classmethod
    def from_settings(cls, s) -> "JiraConfig":
        proj = (s.jira_project_key or "").strip()
        if "/" in proj:
            proj = proj.rstrip("/").split("/")[-1]
        base_url = (s.jira_base_url or "").rstrip("/")
        return cls(base_url, s.jira_user_email, s.jira_api_token, proj,
                   s.jira_issue_type or "Story", s.jira_simulation)


@dataclass
class CreateResult:
    story_id: str
    ok: bool
    key: str = ""
    url: str = ""
    error: str = ""
    simulated: bool = False
    payload: dict = field(default_factory=dict)


def label(text: str) -> str:
    """Jira labels cannot contain spaces or symbols (/, &, ! …) – they cause 400 Bad Request."""
    return re.sub(r"[^a-zA-Z0-9_\-]", "_", str(text).strip())[:30].strip("_") or "RIA"


SIM_BASE_URL = "https://your-domain.atlassian.net"
HAPPY = {"POSITIVE"}


def build_description(story: StoryRecord, requirements: dict[str, RequirementRecord],
                      scenarios: list[TestScenarioRecord]) -> str:
    """Jira wiki (Textile) description: Description, Path or Navigation, Functional Requirement, Acceptance Requirement."""
    out = [
        "h3. Description",
        f"bq. {story.story_text}",
        "",
        "h3. Path or Navigation",
        f"*Navigation:* {story.group} → {story.title}",
        "",
        "h3. Functional Requirement",
    ]
    for rid in story.requirement_ids:
        req = requirements.get(rid)
        title = req.title if req else "title not available"
        desc = f" – {req.description}" if (req and req.description and req.description != title) else ""
        out.append(f"* *{rid}* – {title}{desc}")
    out += ["", "h3. Acceptance Requirement"]
    if story.acceptance_criteria:
        for ac in story.acceptance_criteria:
            out += [f"* *{ac.ac_id}* ({ac.criterion_type.value}):",
                    f"** *Given* {ac.given}", f"** *When* {ac.when}", f"** *Then* {ac.then}"]
    else:
        out.append("_No acceptance criteria yet._")
    out += ["", "h3. QA Test Scenarios"]
    tests = [t for t in scenarios if t.story_id == story.story_id]
    if tests:
        for t in tests:
            kind = "Happy path" if t.scenario_type.value in HAPPY else "Edge case / error handling"
            out.append(f"* *{t.scenario_id}* [{t.priority.value}] {t.title} _({kind})_")
            out += [f"## {step}" for step in t.steps]
            out.append(f"** *Expected:* {t.expected_result}")
    else:
        out.append("_No test scenarios yet._")
    if story.clarification_questions:
        out += ["", "h3. Open questions"] + [f"* {q}" for q in story.clarification_questions]
    out += ["", f"_Generated by Requirement Intelligence Assistant ({story.story_id}). Review before development._"]
    return "\n".join(out)


def build_issue_payload(story: StoryRecord, requirements: dict[str, RequirementRecord],
                        scenarios: list[TestScenarioRecord], cfg: JiraConfig) -> dict:
    summary = (story.title or story.capability or story.story_id).strip()
    if len(summary) > SUMMARY_MAX:
        summary = summary[:SUMMARY_MAX - 1] + "…"
    labels = ["RIA", label(story.group), label(story.story_id)]
    if story.review_status.value in ("APPROVED", "EDITED"):
        labels.append("ria-approved")
    elif story.review_status.value == "PENDING":
        labels.append("needs-review")
    return {"fields": {
        "project": {"key": cfg.project_key or "EXP"},
        "summary": summary,
        "issuetype": {"name": cfg.issue_type or "Story"},
        "description": build_description(story, requirements, scenarios),
        "labels": list(dict.fromkeys(labels)),
    }}


class JiraClient:
    def __init__(self, cfg: JiraConfig, transport: httpx.BaseTransport | None = None, timeout_s: float = 30.0):
        self.cfg = cfg
        self._client = httpx.Client(timeout=timeout_s, transport=transport)

    # ---------------------------------------------------------------- auth / http
    def _headers(self) -> dict[str, str]:
        h = {"Accept": "application/json", "Content-Type": "application/json"}
        if self.cfg.is_cloud:
            token = base64.b64encode(f"{self.cfg.email}:{self.cfg.api_token}".encode()).decode()
            h["Authorization"] = f"Basic {token}"
        else:
            h["Authorization"] = f"Bearer {self.cfg.api_token}"
        return h

    def _url(self, path: str) -> str:
        return f"{self.cfg.base_url.rstrip('/')}{path}"

    @staticmethod
    def _error(resp: httpx.Response) -> str:
        if resp.status_code in (401, 403):
            return f"HTTP {resp.status_code}: authentication or permission failed – check email/token and project access."
        try:
            data = resp.json()
            msgs = list(data.get("errorMessages") or []) + [f"{k}: {v}" for k, v in (data.get("errors") or {}).items()]
            if msgs:
                return f"HTTP {resp.status_code}: " + "; ".join(msgs)
        except ValueError:
            pass
        return f"HTTP {resp.status_code}: {resp.text[:300]}"

    # ---------------------------------------------------------------- API
    def test_connection(self) -> tuple[bool, str]:
        if self.cfg.simulation:
            log.info("Jira connection test: simulation")
            return True, "Simulation mode: no connection made. Payloads are built exactly as in live mode."
        if self.cfg.missing:
            return False, f"Jira is not configured. Set {', '.join(self.cfg.missing)} in .env and restart."
        try:
            me = self._client.get(self._url("/rest/api/2/myself"), headers=self._headers())
            if me.status_code >= 400:
                return False, self._error(me)
            proj = self._client.get(self._url(f"/rest/api/2/project/{self.cfg.project_key}"), headers=self._headers())
            if proj.status_code >= 400:
                return False, f"Connected as {me.json().get('displayName', 'user')}, but project " \
                              f"'{self.cfg.project_key}' is not accessible – {self._error(proj)}"
        except httpx.HTTPError as exc:
            return False, f"Could not reach {self.cfg.base_url} ({type(exc).__name__})."
        return True, (f"Connected as {me.json().get('displayName', 'user')} · project "
                      f"{proj.json().get('name', self.cfg.project_key)} ({self.cfg.project_key}).")

    def create_story(self, story: StoryRecord, requirements: dict[str, RequirementRecord],
                     scenarios: list[TestScenarioRecord], sim_number: int = 1) -> CreateResult:
        payload = build_issue_payload(story, requirements, scenarios, self.cfg)
        if self.cfg.simulation:
            key = f"{self.cfg.project_key or 'EXP'}-{100 + sim_number}"
            base = (self.cfg.base_url or SIM_BASE_URL).rstrip("/")
            return CreateResult(story.story_id, True, key, f"{base}/browse/{key}", simulated=True, payload=payload)
        if self.cfg.missing:
            return CreateResult(story.story_id, False, error=f"Missing settings: {', '.join(self.cfg.missing)}",
                                payload=payload)
        try:
            resp = self._client.post(self._url("/rest/api/2/issue"), headers=self._headers(), json=payload)
        except httpx.HTTPError as exc:
            return CreateResult(story.story_id, False, error=f"Network error: {type(exc).__name__}", payload=payload)
        if resp.status_code not in (200, 201):
            return CreateResult(story.story_id, False, error=self._error(resp), payload=payload)
        key = resp.json().get("key", "")
        return CreateResult(story.story_id, True, key, self._url(f"/browse/{key}"), payload=payload)

    def create_stories(self, stories: list[StoryRecord], requirements: dict[str, RequirementRecord],
                       scenarios: list[TestScenarioRecord], progress=None) -> list[CreateResult]:
        """Create one issue per story. Failures are reported per story; the batch continues.
        ``progress(done, total, result)`` is called after each story (for a Streamlit progress bar)."""
        out = []
        for i, s in enumerate(stories, start=1):
            res = self.create_story(s, requirements, scenarios, sim_number=i)
            (log.info if res.ok else log.warning)("Jira %s: %s -> %s%s", "simulation" if res.simulated else "create",
                                                   res.story_id, res.key or "FAILED",
                                                   f" ({res.error})" if res.error else "")
            out.append(res)
            if progress:
                progress(i, len(stories), res)
        return out
